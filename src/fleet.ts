/**
 * FLEET SCAN — probe a list of URLs, aggregate who is behind what.
 *
 * The single-URL verdict answers "what am I up against on this site". The fleet
 * scan answers the market question: "across N targets, which vendors actually show
 * up, and at which layer do they block". Results render as a markdown report —
 * that's the dataset behind the writeup.
 */

import { probe } from './probe.js';
import { analyze } from './analyze.js';

export interface FleetRow {
  url: string;
  status: number | null;
  verdict: 'blocked' | 'present' | 'clean' | 'error';
  challenge: string;
  layer: string;
  vendors: string[];
  elapsedMs: number;
  error?: string;
}

export interface FleetStats {
  total: number;
  blocked: number;
  present: number;
  clean: number;
  errors: number;
  byVendor: Record<string, number>;
  /** block counts by layer — the "where do you actually get stopped" table */
  byLayer: Record<string, number>;
}

export interface FleetResult {
  rows: FleetRow[];
  stats: FleetStats;
  elapsedMs: number;
}

/** one URL per line; blanks and `#` comments skipped; scheme added if missing */
export function normalizeUrl(line: string): string | null {
  const t = line.trim();
  if (!t || t.startsWith('#')) return null;
  return /^https?:\/\//i.test(t) ? t : `https://${t}`;
}

export function computeStats(rows: FleetRow[]): FleetStats {
  const stats: FleetStats = {
    total: rows.length,
    blocked: 0,
    present: 0,
    clean: 0,
    errors: 0,
    byVendor: {},
    byLayer: {},
  };
  for (const r of rows) {
    stats[r.verdict === 'error' ? 'errors' : r.verdict]++;
    for (const v of r.vendors) stats.byVendor[v] = (stats.byVendor[v] ?? 0) + 1;
    if (r.verdict === 'blocked') stats.byLayer[r.layer] = (stats.byLayer[r.layer] ?? 0) + 1;
  }
  return stats;
}

async function probeOne(url: string, timeoutMs?: number): Promise<FleetRow> {
  try {
    const p = await probe(url, { timeoutMs });
    const v = analyze({ status: p.status, headers: p.headers, body: p.body, url: p.finalUrl, redirectChain: p.redirectChain, elapsedMs: p.elapsedMs });
    return {
      url,
      status: p.status,
      verdict: v.blocked ? 'blocked' : v.challenge.kind !== 'none' ? 'present' : 'clean',
      challenge: v.challenge.kind,
      layer: v.layer,
      vendors: v.vendors.map((x) => x.name),
      elapsedMs: p.elapsedMs,
    };
  } catch (err) {
    return {
      url,
      status: null,
      verdict: 'error',
      challenge: '-',
      layer: '-',
      vendors: [],
      elapsedMs: 0,
      error: err instanceof Error ? err.message : String(err),
    };
  }
}

export async function scanUrls(
  urls: string[],
  opts: { concurrency?: number; timeoutMs?: number; onProgress?: (done: number, total: number, row: FleetRow) => void } = {},
): Promise<FleetResult> {
  const concurrency = opts.concurrency ?? 4;
  const started = Date.now();
  const rows: FleetRow[] = new Array(urls.length);
  let next = 0;
  let done = 0;

  async function worker(): Promise<void> {
    while (next < urls.length) {
      const i = next++;
      const row = await probeOne(urls[i], opts.timeoutMs);
      rows[i] = row;
      opts.onProgress?.(++done, urls.length, row);
    }
  }

  await Promise.all(Array.from({ length: Math.min(concurrency, urls.length) }, worker));
  return { rows, stats: computeStats(rows), elapsedMs: Date.now() - started };
}

function sortedEntries(rec: Record<string, number>): [string, number][] {
  return Object.entries(rec).sort((a, b) => b[1] - a[1]);
}

export function renderMarkdownReport(res: FleetResult): string {
  const { rows, stats } = res;
  const pct = (n: number) => (stats.total ? Math.round((n / stats.total) * 100) : 0);
  const lines: string[] = [
    '# whichwaf fleet report',
    '',
    `_Scanned ${new Date().toISOString().slice(0, 10)} · ${stats.total} URLs · ${Math.round(res.elapsedMs / 1000)}s_`,
    '',
    '## Summary',
    '',
    `- **blocked:** ${stats.blocked} (${pct(stats.blocked)}%)`,
    `- **present** (vendor in stack, not blocking): ${stats.present} (${pct(stats.present)}%)`,
    `- **clean:** ${stats.clean} (${pct(stats.clean)}%)`,
    `- **errors:** ${stats.errors}`,
    '',
    '## Vendors in the stack',
    '',
    '| vendor | sites |',
    '|---|---|',
    ...sortedEntries(stats.byVendor).map(([v, n]) => `| ${v} | ${n} |`),
    '',
    '## Where blocks happen (layer)',
    '',
    '| layer | blocks |',
    '|---|---|',
    ...sortedEntries(stats.byLayer).map(([l, n]) => `| ${l} | ${n} |`),
    '',
    '## Details',
    '',
    '| url | status | verdict | challenge | layer | vendors |',
    '|---|---|---|---|---|---|',
    ...rows.map(
      (r) =>
        `| ${r.url} | ${r.status ?? r.error ?? 'error'} | ${r.verdict} | ${r.challenge} | ${r.layer} | ${r.vendors.join(', ') || '—'} |`,
    ),
    '',
    '_Generated by whichwaf — evidence-based anti-bot/WAF detection._',
  ];
  return lines.join('\n');
}
